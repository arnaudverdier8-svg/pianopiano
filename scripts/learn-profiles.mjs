// Measures average partial-amplitude profiles from the Salamander Grand Piano samples (Yamaha C5,
// CC-BY 3.0) bundled for playback, and writes src/audio/detector/partial-profiles.ts.
// The detector benchmark uses *different* recordings (University of Iowa, Steinway B), so the
// dictionary is never fitted to the audio it is evaluated on. Needs ffmpeg.
//   node scripts/learn-profiles.mjs
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';

const RATE = 22050;
const N = 16384;
const K = 16;
const NAMES = { C: 0, Ds: 3, Fs: 6, A: 9 };

function fftMag(x) {
  const n = x.length, re = Float64Array.from(x), im = new Float64Array(n);
  for (let i = 1, j = 0; i < n; i++) { let bit = n >> 1; for (; j & bit; bit >>= 1) j ^= bit; j ^= bit; if (i < j) { [re[i], re[j]] = [re[j], re[i]]; } }
  for (let len = 2; len <= n; len <<= 1) {
    const ang = -2 * Math.PI / len;
    for (let i = 0; i < n; i += len) for (let k = 0; k < len / 2; k++) {
      const wr = Math.cos(ang * k), wi = Math.sin(ang * k), a = i + k, b = a + len / 2;
      const xr = re[b] * wr - im[b] * wi, xi = re[b] * wi + im[b] * wr;
      re[b] = re[a] - xr; im[b] = im[a] - xi; re[a] += xr; im[a] += xi;
    }
  }
  return Array.from({ length: n / 2 }, (_, i) => Math.hypot(re[i], im[i]));
}
const inharm = (m) => Math.pow(2, m > 45 ? -13 + ((m - 45) / 12) * 0.95 : -13 + ((45 - m) / 12) * 0.4);

const rows = [];
for (const f of readdirSync('public/samples/salamander').filter((f) => f.endsWith('.mp3'))) {
  const [, n, o] = f.match(/^([A-Z]s?)(\d)\.mp3$/);
  const midi = 12 * (Number(o) + 1) + NAMES[n];
  const raw = execFileSync('ffmpeg', ['-v', 'error', '-i', `public/samples/salamander/${f}`, '-ac', '1', '-ar', String(RATE), '-f', 'f32le', '-'], { maxBuffer: 1 << 28 });
  const pcm = new Float32Array(raw.buffer, raw.byteOffset, raw.byteLength / 4);
  let peak = 0; for (const v of pcm) peak = Math.max(peak, Math.abs(v));
  const onset = pcm.findIndex((v) => Math.abs(v) > peak * 0.1);
  // Attack-to-early-decay segment, Hann windowed (what the detector sees in its first ~200 ms).
  const seg = new Float64Array(N);
  const len = Math.min(N, Math.round(0.3 * RATE));
  for (let i = 0; i < len; i++) seg[i] = (pcm[onset + i] ?? 0) * (0.5 - 0.5 * Math.cos((2 * Math.PI * i) / len));
  const mag = fftMag(seg);
  const f0 = 440 * Math.pow(2, (midi - 69) / 12);
  const B = inharm(midi);
  const amps = [];
  for (let k = 1; k <= K; k++) {
    const fk = k * f0 * Math.sqrt(1 + B * k * k);
    if (fk > 9000) { amps.push(0); continue; }
    const lo = Math.floor((fk * Math.pow(2, -0.4 / 12) * N) / RATE), hi = Math.ceil((fk * Math.pow(2, 0.4 / 12) * N) / RATE);
    let m = 0; for (let b = lo; b <= hi; b++) m = Math.max(m, mag[b] ?? 0);
    amps.push(m);
  }
  const max = Math.max(...amps);
  rows.push({ midi, amps: amps.map((a) => +(a / max).toFixed(3)) });
}
rows.sort((a, b) => a.midi - b.midi);
const body = rows.map((r) => `  [${r.midi}, [${r.amps.join(', ')}]],`).join('\n');
writeFileSync('src/audio/detector/partial-profiles.ts', `// Generated by scripts/learn-profiles.mjs — do not edit.
// Relative partial amplitudes (partials 1..${K}, peak = 1) of the attack segment of each Salamander
// Grand Piano sample (Yamaha C5, Alexander Holm, CC-BY 3.0). Used only to shape the dictionary;
// detector tests use independent University of Iowa recordings.
export const PARTIAL_PROFILES: [number, number[]][] = [
${body}
];
`);
